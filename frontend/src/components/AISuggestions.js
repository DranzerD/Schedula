/**
 * AISuggestions Component
 * Daily briefing + coaching suggestions from GET /api/schedule/suggestions.
 * The server uses Groq when configured and deterministic rules otherwise;
 * the badge shows which one produced the text.
 */

import React, { useState, useEffect, useCallback } from "react";
import { scheduleAPI } from "../services/api";

const suggestionStyles = {
  warning: "bg-amber-50 border-amber-400 text-amber-900",
  alert: "bg-red-50 border-red-400 text-red-900",
  tip: "bg-indigo-50 border-indigo-400 text-indigo-900",
  insight: "bg-purple-50 border-purple-400 text-purple-900",
  reminder: "bg-blue-50 border-blue-400 text-blue-900",
};

const SourceBadge = ({ source }) => (
  <span
    title={
      source === "groq"
        ? "Wording generated by Groq and checked against your real schedule numbers"
        : "Generated by deterministic rules"
    }
    className={`px-2 py-0.5 text-[10px] font-bold uppercase tracking-wide rounded-full ${
      source === "groq"
        ? "bg-emerald-100 text-emerald-700"
        : "bg-gray-100 text-gray-500"
    }`}
  >
    {source === "groq" ? "⚡ Groq" : "Rules"}
  </span>
);

const AISuggestions = ({ date, refreshKey }) => {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(false);
  const [expanded, setExpanded] = useState(true);

  const load = useCallback(async () => {
    setLoading(true);
    setError(false);
    try {
      const response = await scheduleAPI.getSuggestions(date);
      setData(response.data.data);
    } catch (err) {
      setError(true);
    } finally {
      setLoading(false);
    }
  }, [date]);

  useEffect(() => {
    load();
  }, [load, refreshKey]);

  if (loading && !data) {
    return (
      <div className="bg-white rounded-2xl shadow-sm border border-gray-100 p-4">
        <div className="flex items-center gap-3">
          <div className="w-8 h-8 rounded-full bg-gradient-to-r from-indigo-500 to-purple-500 animate-pulse"></div>
          <div className="flex-1">
            <div className="h-4 bg-gray-200 rounded animate-pulse w-32 mb-2"></div>
            <div className="h-3 bg-gray-100 rounded animate-pulse w-48"></div>
          </div>
        </div>
      </div>
    );
  }

  if (error || !data) return null;

  const suggestions = data.suggestions || [];

  return (
    <div className="bg-white rounded-2xl shadow-sm border border-gray-100 overflow-hidden">
      <button
        onClick={() => setExpanded(!expanded)}
        className="w-full p-4 flex items-center justify-between hover:bg-gray-50 transition-colors"
      >
        <div className="flex items-center gap-3">
          <div className="w-8 h-8 rounded-full bg-gradient-to-r from-indigo-500 to-purple-500 flex items-center justify-center">
            <span className="text-white text-sm">✨</span>
          </div>
          <div className="text-left">
            <h3 className="font-semibold text-gray-900 flex items-center gap-2">
              AI Insights <SourceBadge source={data.source} />
            </h3>
            <p className="text-xs text-gray-500">
              {suggestions.length} suggestion
              {suggestions.length === 1 ? "" : "s"}
            </p>
          </div>
        </div>
        <svg
          className={`w-5 h-5 text-gray-400 transition-transform ${expanded ? "rotate-180" : ""}`}
          fill="none"
          stroke="currentColor"
          viewBox="0 0 24 24"
        >
          <path
            strokeLinecap="round"
            strokeLinejoin="round"
            strokeWidth={2}
            d="M19 9l-7 7-7-7"
          />
        </svg>
      </button>

      {expanded && (
        <>
          {data.briefing && (
            <p className="px-4 pb-3 text-sm text-gray-700 border-t border-gray-100 pt-3">
              {data.briefing}
            </p>
          )}
          <div className="border-t border-gray-100 divide-y divide-gray-100">
            {suggestions.map((s) => (
              <div
                key={s.id}
                className={`p-4 border-l-4 ${suggestionStyles[s.type] || suggestionStyles.tip}`}
              >
                <div className="flex items-start gap-3">
                  <span className="text-xl flex-shrink-0">{s.icon}</span>
                  <div className="flex-1 min-w-0">
                    <h4 className="font-medium text-sm">{s.title}</h4>
                    <p className="text-xs mt-1 opacity-80">{s.message}</p>
                  </div>
                </div>
              </div>
            ))}
          </div>
          <div className="p-3 border-t border-gray-100 bg-gray-50">
            <button
              onClick={load}
              disabled={loading}
              className="w-full text-center text-xs text-gray-500 hover:text-indigo-600 transition-colors disabled:opacity-50"
            >
              {loading ? "Refreshing…" : "🔄 Refresh insights"}
            </button>
          </div>
        </>
      )}
    </div>
  );
};

export default AISuggestions;
